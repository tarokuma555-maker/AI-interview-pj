import assert from "node:assert/strict";
import { BASE_URL, agentLogin, openPhone } from "./browser.mjs";
const { page, shot, finish } = await openPhone("agent-seekers");
await agentLogin(page, "seeker-a@example.com");
await page.getByRole("link", { name: "+ 求職者を追加", exact: true }).click();
await page.getByLabel("名前", { exact: true }).fill("テスト花子");
await page.getByLabel("職種", { exact: true }).fill("看護師");
await page.getByLabel("経歴", { exact: true }).fill("内科病棟8年");
await page.getByLabel("転職理由", { exact: true }).fill("新しい分野に挑戦");
await shot("new-seeker");
await page.getByRole("button", { name: "保存する", exact: true }).click();
await page.waitForURL(/\/seekers\/[a-f0-9-]+$/);
const detail = page.url();
await page.getByRole("link", { name: "+ 応募先を追加してリンクを作る" }).click();
await page.getByLabel("病院・会社の名前", { exact: true }).fill("架空総合病院");
await page.getByLabel("職種・配属先", { exact: true }).fill("病棟看護師");
await page.getByLabel("求人票の内容").fill("病棟での看護業務");
await shot("new-link");
await page.getByRole("button", { name: "招待リンクを作る", exact: true }).click();
await page.getByText("招待リンクを作りました。LINE やメールで求職者に送ってください。", { exact: true }).waitFor();
const url = await page.getByTestId("created-link-url").textContent();
assert.match(url, /\/i#[A-Za-z0-9_-]{22}$/);
await page.context().grantPermissions(["clipboard-read", "clipboard-write"], { origin: BASE_URL });
await page.getByRole("button", { name: "リンクをコピー", exact: true }).first().click();
await page.getByRole("button", { name: "コピーしました", exact: true }).waitFor();
assert.equal(await page.evaluate(() => navigator.clipboard.readText()), url);
await shot("created-link");
await page.getByRole("link", { name: "内容修正", exact: true }).click();
await page.getByLabel("職種・配属先", { exact: true }).fill("外来看護師");
await page.getByRole("button", { name: "保存する", exact: true }).click();
await page.getByText("外来看護師", { exact: true }).waitFor();
await page.getByRole("button", { name: "リンクをコピー", exact: true }).click();
await page.getByRole("button", { name: "コピーしました", exact: true }).waitFor();
assert.equal(await page.evaluate(() => navigator.clipboard.readText()), url);
await page.getByRole("button", { name: "URL停止", exact: true }).click();
await page.getByText("停止中", { exact: true }).waitFor();
assert.equal(await page.getByRole("button", { name: /リンクをコピー|コピーしました/ }).count(), 0);
await shot("disabled");
await page.getByRole("button", { name: "使えるようにする", exact: true }).click();
await page.getByRole("button", { name: "リンクをコピー", exact: true }).waitFor();
// クリップボードが使えない環境でも同じリンクを選択できる。
await page.evaluate(() => { navigator.clipboard.writeText = async () => { throw new Error("unavailable"); }; });
await page.getByRole("button", { name: "リンクをコピー", exact: true }).click();
await page.getByText("長押ししてコピーしてください", { exact: true }).waitFor();
assert.equal(await page.getByLabel("コピーする招待リンク").inputValue(), url);
await shot("copy-fallback");
await page.getByRole("link", { name: "担当の求職者へ", exact: true }).click();
await page.getByText("応募先 1件", { exact: true }).waitFor();
await shot("list");
await page.goto(detail);
await page.getByRole("link", { name: "求職者の情報を直す", exact: true }).click();
await page.getByLabel("名前", { exact: true }).fill("テスト花子改");
await page.getByRole("button", { name: "保存する", exact: true }).click();
await page.getByRole("heading", { name: "テスト花子改", exact: true }).waitFor();
const other = await openPhone("agent-other");
await agentLogin(other.page, "seeker-b@example.com");
for (const path of [detail, `${detail}/edit`, `${detail}/links/new`]) {
  await other.page.goto(path);
  await other.page.getByRole("heading", { name: "この求職者は見つかりません" }).waitFor();
  assert.equal(await other.page.getByText("テスト花子改", { exact: true }).count(), 0);
}
await other.shot("not-owner"); await other.finish();
await page.getByRole("button", { name: "この求職者を削除", exact: true }).click();
await page.getByText(/元に戻せません/).waitFor();
await page.getByRole("button", { name: "やめる", exact: true }).click();
await page.getByRole("heading", { name: "テスト花子改", exact: true }).waitFor();
await page.getByRole("button", { name: "この求職者を削除", exact: true }).click();
await shot("delete-confirm");
await page.getByRole("button", { name: "削除する", exact: true }).click();
await page.waitForURL(/\/agent$/);
await page.getByText("まだ求職者がいません。", { exact: true }).waitFor();
await shot("deleted");
await finish();
